param(
    [string]$Fxc = ''
)
# Compile the Present-pass HLSL into inject\present\*.dxbc and the embedded header.
#
# NOTE: these Present payloads are compiled with /O3 (ps_5_0). The tonemap/SSAO
# payloads in tools\build_tonemap.ps1 intentionally use ps_4_0 WITHOUT /O3 so
# they reproduce the shipped bytes. Keep the two build contracts separate.
$ErrorActionPreference = 'Stop'

if (-not $Fxc) {
    $roots = @(
        'C:\Program Files (x86)\Windows Kits\10\bin',
        'C:\Program Files\Windows Kits\10\bin'
    ) | Where-Object { Test-Path $_ }
    $cand = foreach ($r in $roots) {
        Get-ChildItem $r -Directory -ErrorAction SilentlyContinue | ForEach-Object {
            $p = Join-Path $_.FullName 'x64\fxc.exe'
            if (Test-Path $p) { [pscustomobject]@{ Ver = [version]$_.Name; Path = $p } }
        }
    }
    $Fxc = ($cand | Sort-Object Ver -Descending | Select-Object -First 1).Path
}
if (-not $Fxc -or -not (Test-Path -LiteralPath $Fxc)) { throw 'fxc.exe not found; pass -Fxc <path> or install the Windows SDK' }
Write-Host "fxc: $Fxc" -ForegroundColor DarkGray

$dir = Join-Path (Split-Path $PSScriptRoot -Parent) 'inject\present'
$src = Join-Path $dir 'fullscreen.hlsl'
$jobs = @(
    @{ e = 'VSMain';      t = 'vs_5_0'; f = 'fullscreen_vs.dxbc'   },
    @{ e = 'PSDepth';     t = 'ps_5_0'; f = 'fullscreen_ps.dxbc'   },
    @{ e = 'PSDepthMS';   t = 'ps_5_0'; f = 'fullscreen_psms.dxbc' },
    @{ e = 'PSComposite'; t = 'ps_5_0'; f = 'fullscreen_ao.dxbc'   }
)
foreach ($j in $jobs) {
    $out = Join-Path $dir $j.f
    & $Fxc /nologo /T $j.t /E $j.e /O3 /Fo $out $src
    if ($LASTEXITCODE -ne 0) { throw ("fxc failed for " + $j.e) }
    $len = (Get-Item -LiteralPath $out).Length
    Write-Host ("compiled " + $j.e + " -> " + $j.f + " (" + $len + " bytes)")
}

function Emit($name, $file, $sizename) {
    $bytes = [System.IO.File]::ReadAllBytes((Join-Path $dir $file))
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.Append("static const unsigned char " + $name + "[] = {")
    for ($i = 0; $i -lt $bytes.Length; $i++) {
        if ($i -gt 0) { [void]$sb.Append(",") }
        [void]$sb.Append("0x" + $bytes[$i].ToString("x2"))
    }
    [void]$sb.Append("};")
    [void]$sb.Append([Environment]::NewLine)
    [void]$sb.Append("static const unsigned int  " + $sizename + " = " + $bytes.Length + ";")
    [void]$sb.Append([Environment]::NewLine)
    return $sb.ToString()
}

$h = New-Object System.Text.StringBuilder
[void]$h.Append("#pragma once" + [Environment]::NewLine + "// auto-generated by tools/build_present.ps1" + [Environment]::NewLine)
[void]$h.Append((Emit 'kFullscreenVS'   'fullscreen_vs.dxbc'   'kFullscreenVSSize'))
[void]$h.Append((Emit 'kFullscreenPS'   'fullscreen_ps.dxbc'   'kFullscreenPSSize'))
[void]$h.Append((Emit 'kFullscreenPSMS' 'fullscreen_psms.dxbc' 'kFullscreenPSMSSize'))
[void]$h.Append((Emit 'kFullscreenPSAO' 'fullscreen_ao.dxbc'   'kFullscreenPSAOSize'))
$hpath = Join-Path $dir 'fullscreen_shaders.h'
[System.IO.File]::WriteAllText($hpath, $h.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("header written: " + $hpath)
