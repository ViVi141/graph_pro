import struct, json
from capstone import *
from capstone.x86 import *
EXE = r"D:\SteamLibrary\steamapps\common\Arma 3\Arma3_x64.exe"
data = open(EXE, "rb").read()
e = struct.unpack_from("<I", data, 0x3C)[0]; coff = e + 4
nsec = struct.unpack_from("<H", data, coff + 2)[0]; opt = coff + 20
ib = struct.unpack_from("<Q", data, opt + 24)[0]
sec_off = opt + struct.unpack_from("<H", data, coff + 16)[0]
secs = []
for i in range(nsec):
    o = sec_off + i * 40
    nm = data[o:o+8].rstrip(b"\0").decode("latin-1","ignore")
    vs, va, rs, ra = struct.unpack_from("<IIII", data, o + 8)
    secs.append((nm, va, vs, ra, rs))
def off(rva):
    for nm, va, vs, ra, rs in secs:
        if va <= rva < va + vs: return ra + (rva - va)
pd = [s for s in secs if s[0] == ".pdata"][0]
_, pv, pvs, pra, prs = pd
fmap = {}
for i in range(0, prs, 12):
    b, e2, u = struct.unpack_from("<III", data, pra + i)
    if b: fmap[b] = e2
md = Cs(CS_ARCH_X86, CS_MODE_64); md.detail = True
cands = json.load(open(r"C:\Users\74738\Desktop\Projects\Arma3\graph_pro\extract\candidates.json"))
safe = []
for c in cands:
    rva, size = c["rva"], c["size"]
    insns = list(md.disasm(data[off(rva):off(rva)+size], ib + rva))
    total = 0; ok = True; cl = 0
    for i in insns:
        if i.mnemonic in ("jmp","call","ret","je","jne","jg","jl","jae","jbe","js","jns","loop"):
            ok = False
        for op in i.operands:
            if op.type == X86_OP_MEM and op.mem.base == X86_REG_RIP: ok = False
        total += i.size
        if total >= 5: cl = total; break
    if not ok or cl == 0 or cl > 16: continue
    safe.append(dict(rva=rva, copy_len=cl, size=size, simd=c["simd"]))
print("final candidates:", len(safe))
lines = ["// auto-generated by tools/gen_cand_header.py",
         "#pragma once",
         "struct CandHook { unsigned rva; unsigned copyLen; volatile long count; };",
         "static CandHook g_cands[] = {"]
for c in safe:
    lines.append("    { 0x%08X, %d, 0 },   // size %d, simd %d" % (c["rva"], c["copy_len"], c["size"], c["simd"]))
lines.append("};")
lines.append("static const int g_nCand = sizeof(g_cands)/sizeof(g_cands[0]);")
path = r"C:\Users\74738\Desktop\Projects\Arma3\graph_pro\inject\proxy\cand_hooks.h"
open(path, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote", path, "entries", len(safe))
